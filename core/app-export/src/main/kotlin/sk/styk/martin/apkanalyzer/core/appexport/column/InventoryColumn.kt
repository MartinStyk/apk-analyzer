    InstallerPackage(
        "installer_package",
        InventoryColumnGroup.Installation,
        InventoryDataSource.AppList,
    ),
    InstallInitiator(
        "install_initiator",
        InventoryColumnGroup.Installation,
        InventoryDataSource.AppList,
    ),
