package sk.styk.martin.apkanalyzer.core.appexport.column

import sk.styk.martin.apkanalyzer.core.appexport.source.InventoryDataSource

enum class InventoryColumnGroup {
    Identification,
    Versioning,
    ApiTargets,
    Installation,
    Storage,
    Security,
    Signing,
    Permissions,
    Components,
    Requirements,
    Manifest,
}

enum class InventoryColumnShape {
    Scalar,
    Structured,
}

